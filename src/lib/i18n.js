export const DICTS = { es, en };

export function detectLang(search = '', nav = {}) {
  const q = new URLSearchParams(search).get('lang');
  if (q === 'es' || q === 'en') return q;
  return (nav.language || '').toLowerCase().startsWith('es') ? 'es' : 'en';
}

export function translate(lang, key, params = {}) {
  const dict = DICTS[lang] || es;
  const s = dict[key] ?? es[key] ?? key;
  return s.replace(/\{(\w+)\}/g, (_, k) => (params[k] ?? `{${k}}`));
}

export function eventText(lang, e) {
  return translate(lang, `ev.${e.kind}`, e.params);
}
